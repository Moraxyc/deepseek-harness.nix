#!/usr/bin/env bash
set -euo pipefail

repo_root=$(git rev-parse --show-toplevel)
docs_dir="$repo_root/docs"
tmp_dir=$(mktemp -d)
check_mode=0
locales=()

cleanup() {
  rm -rf "$tmp_dir"
}
trap cleanup EXIT

while [ "$#" -gt 0 ]; do
  case "$1" in
    --check)
      check_mode=1
      ;;
    --lang)
      shift
      case "${1:-}" in
        en)
          locales=(en)
          ;;
        zh-CN)
          locales=(zh-CN)
          ;;
        *)
          echo "unsupported locale: ${1:-}; expected en or zh-CN" >&2
          exit 1
          ;;
      esac
      ;;
    *)
      echo "usage: generate-docs [--check] [--lang en|zh-CN]" >&2
      exit 1
      ;;
  esac
  shift
done

if [ "${#locales[@]}" -eq 0 ]; then
  locales=(en zh-CN)
fi

catalog=$(
  # shellcheck disable=SC2016
  nix eval --impure --json --expr '
    let
      repo = toString ./.;
      flake = builtins.getFlake repo;
      system = builtins.currentSystem;
      scope = flake.legacyPackages.${system};
    in
    import ./lib/catalog.nix { inherit scope; }
  '
)

mkdir -p "$docs_dir"

render_en() {
  local output=$1

  {
    cat <<'EOF'
# Bundles and Presets

This catalog is generated from the flake. Do not edit this file by hand.

Run `nix run .#generate-docs` after changing bundle or preset expressions.
Use `nix run .#generate-docs -- --check` to verify the checked-in catalog.

## Bundles

| Flake output | Package | Version | Description |
|---|---|---|---|
EOF
    jq -r '
      .bundles[] |
      "| `bundles.\(.name)` | `\(.package)` | \(.version // "-") | \(.description // "-" | gsub("[|]"; "\\|")) |"
    ' <<<"$catalog"
    cat <<'EOF'

## Presets

| Flake output | Default profile | Bundles | Description |
|---|---|---|---|
EOF
    jq -r '
      .presets[] |
      "| `presets.\(.name)` | \(if .defaultProfile then "`\(.defaultProfile)`" else "-" end) | \([.bundles[] | "`" + . + "`"] | join(", ")) | \(.description // "-" | gsub("[|]"; "\\|")) |"
    ' <<<"$catalog"
  } > "$output"
}

render_zh() {
  local output=$1

  {
    cat <<'EOF'
# Bundles 和预设

本目录由 flake 自动生成。请勿手工编辑。

修改 bundle 或 preset 表达式后运行 `nix run .#generate-docs`。
可使用 `nix run .#generate-docs -- --lang zh-CN --check` 校验中文目录。

## Bundles

| Flake 输出 | 包 | 版本 | 说明 |
|---|---|---|---|
EOF
    jq -r '
      .bundles[] |
      "| `bundles.\(.name)` | `\(.package)` | \(.version // "-") | \(.descriptionZh // "-" | gsub("[|]"; "\\|")) |"
    ' <<<"$catalog"
    cat <<'EOF'

## 预设

| Flake 输出 | 默认 profile | Bundles | 说明 |
|---|---|---|---|
EOF
    jq -r '
      .presets[] |
      "| `presets.\(.name)` | \(if .defaultProfile then "`\(.defaultProfile)`" else "-" end) | \([.bundles[] | "`" + . + "`"] | join(", ")) | \(.descriptionZh // "-" | gsub("[|]"; "\\|")) |"
    ' <<<"$catalog"
  } > "$output"
}

render() {
  local locale=$1
  local output=$2
  local tmp_file
  tmp_file="$tmp_dir/$(basename "$output")"

  if [ "$locale" = "zh-CN" ]; then
    render_zh "$tmp_file"
  else
    render_en "$tmp_file"
  fi

  prettier --parser markdown --write "$tmp_file" >/dev/null

  if [ "$check_mode" -eq 1 ]; then
    if ! diff -u "$output" "$tmp_file"; then
      echo "$output is stale; run: nix run .#generate-docs" >&2
      exit 1
    fi
  else
    mv "$tmp_file" "$output"
    echo "updated $output"
  fi
}

for locale in "${locales[@]}"; do
  if [ "$locale" = "zh-CN" ]; then
    render zh-CN "$docs_dir/bundles-presets.zh-CN.md"
  else
    render en "$docs_dir/bundles-presets.md"
  fi
done
